using System.Diagnostics;
using System.IO.Compression;
using KaraokeToMp4.Cdg;
using KaraokeToMp4.Midi;
using KaraokeToMp4.Video;

namespace KaraokeToMp4.Metadata;

/// <summary>Works out a song's title and artist from the data inside a karaoke file.</summary>
public static class SongInfoReader
{
    /// <summary>
    /// Text that is clearly not a title or artist: copyright lines, sequencer credits, web addresses,
    /// file-type markers and generic track names.
    /// </summary>
    private static readonly string[] JunkFragments =
    {
        "©", "(c)", "(p)", "℗", "copyright", "all rights", "sequenc", "programmed", "arranged by", "transcribed",
        "created by", "converted", "edited by", "http", "www.", ".com", ".net", ".org", "@", "tune 1000", "tune1000",
        "karaoke", "kmidi", "midi file", "soft karaoke", "generated by",
    };

    private static readonly HashSet<string> GenericNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "words", "lyrics", "lyric", "melody", "vocal", "vocals", "voice", "untitled", "track", "track 1", "track 0",
        "tempo", "tempo track", "conductor", "control", "info", "information", "title", "artist", "song", "unknown",
    };

    /// <summary>Reads song info from a KAR/MIDI file.</summary>
    /// <remarks>
    /// <list type="number">
    /// <item>KAR files: the "@T" lines. The first is the title, the second the artist (Soft Karaoke convention).</item>
    /// <item>Other MIDI files with lyrics (e.g. Tune 1000): the Text events that come before the first lyric,
    /// in order title then artist, skipping copyright/credit lines.</item>
    /// <item>Fallback for the title: the sequence name of the first track.</item>
    /// </list>
    /// </remarks>
    public static SongInfo FromMidi(StandardMidiFile midi)
    {
        var texts = midi.Events
            .Where(e => e.IsMeta && e.MetaType == StandardMidiFile.MetaText)
            .Select(e => (e.Tick, e.Track, Text: MidiLyricExtractor.DecodeText(e.Data)))
            .ToList();

        var karTitles = texts
            .Where(t => t.Text.StartsWith("@T", StringComparison.OrdinalIgnoreCase))
            .Select(t => t.Text[2..].Trim())
            .Where(t => t.Length > 0)
            .ToList();
        if (karTitles.Count > 0)
        {
            var usable = karTitles.Where(IsUsable).ToList();
            if (usable.Count > 0)
                return new SongInfo(usable[0], usable.Count > 1 ? usable[1] : null, "KAR @T tags");
        }

        // Header text before the first sung syllable.
        var lyricTicks = midi.Events.Where(e => e.IsMeta && e.MetaType == StandardMidiFile.MetaLyric).Select(e => e.Tick).ToList();
        long firstLyric = lyricTicks.Count > 0 ? lyricTicks.Min() : long.MaxValue;
        if (lyricTicks.Count > 0)
        {
            var header = texts
                .Where(t => t.Tick < firstLyric || (t.Tick == firstLyric && t.Track != LyricTrack(midi)))
                .Select(t => Tidy(t.Text))
                .Where(IsUsable)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
            if (header.Count > 0)
                return new SongInfo(header[0], header.Count > 1 ? header[1] : null, "MIDI text events");
        }

        var seqName = midi.Events
            .Where(e => e.IsMeta && e.MetaType == StandardMidiFile.MetaTrackName && e.Track == 0)
            .Select(e => Tidy(MidiLyricExtractor.DecodeText(e.Data)))
            .FirstOrDefault(IsUsable);
        return seqName != null ? new SongInfo(seqName, null, "MIDI sequence name") : SongInfo.Empty;
    }

    /// <summary>Reads song info from an audio file: ID3 tags for MP3, otherwise ffprobe (if available).</summary>
    public static async Task<SongInfo> FromAudioAsync(string audioPath, FfmpegTools? tools, CancellationToken ct = default)
    {
        if (audioPath.EndsWith(".mp3", StringComparison.OrdinalIgnoreCase))
        {
            try
            {
                var id3 = Id3Reader.Read(audioPath);
                if (!id3.IsEmpty) return id3;
            }
            catch (IOException) { /* fall through to ffprobe */ }
        }
        return tools != null ? await FromFfprobeAsync(tools, audioPath, ct).ConfigureAwait(false) : SongInfo.Empty;
    }

    /// <summary>Reads song info from any supported karaoke input.</summary>
    /// <param name="tools">Used for tags in non-MP3 audio; may be null.</param>
    public static async Task<SongInfo> ReadAsync(string inputPath, FfmpegTools? tools, CancellationToken ct = default)
    {
        try
        {
            switch (KaraokeConverter.DetectFormat(inputPath))
            {
                case KaraokeFormat.Kar:
                case KaraokeFormat.MidiWithLyrics:
                    return FromMidi(StandardMidiFile.FromFile(inputPath));

                case KaraokeFormat.Mp3Cdg:
                    var ext = Path.GetExtension(inputPath).ToLowerInvariant();
                    if (ext == ".zip") return FromZip(inputPath);
                    var audio = ext == ".cdg" ? CdgConverter.FindAudioForCdg(inputPath) : inputPath;
                    return audio == null ? SongInfo.Empty : await FromAudioAsync(audio, tools, ct).ConfigureAwait(false);
            }
        }
        catch (Exception ex) when (ex is IOException or InvalidDataException or UnauthorizedAccessException)
        {
            // Unreadable metadata shouldn't stop a conversion.
        }
        return SongInfo.Empty;
    }

    private static SongInfo FromZip(string zipPath)
    {
        using var zip = ZipFile.OpenRead(zipPath);
        var mp3 = zip.Entries.FirstOrDefault(e => e.Name.EndsWith(".mp3", StringComparison.OrdinalIgnoreCase));
        if (mp3 == null) return SongInfo.Empty;

        // Zip entry streams can't seek; buffer the (few MB) MP3 so the ID3v1 tag at the end can be read too.
        using var ms = new MemoryStream();
        using (var s = mp3.Open())
            s.CopyTo(ms);
        ms.Position = 0;
        return Id3Reader.Read(ms);
    }

    private static async Task<SongInfo> FromFfprobeAsync(FfmpegTools tools, string path, CancellationToken ct)
    {
        try
        {
            var psi = new ProcessStartInfo(tools.FfprobePath)
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            };
            foreach (var a in new[] { "-v", "error", "-show_entries", "format_tags=title,artist,album_artist", "-of", "default=nw=1", path })
                psi.ArgumentList.Add(a);
            using var p = Process.Start(psi);
            if (p == null) return SongInfo.Empty;
            var stdout = p.StandardOutput.ReadToEndAsync(ct);
            _ = p.StandardError.ReadToEndAsync(ct);
            await p.WaitForExitAsync(ct).ConfigureAwait(false);

            string? title = null, artist = null, albumArtist = null;
            foreach (var line in (await stdout.ConfigureAwait(false)).Split('\n'))
            {
                int eq = line.IndexOf('=');
                if (eq <= 0) continue;
                var key = line[..eq].Trim().ToLowerInvariant().Replace("tag:", "");
                var value = line[(eq + 1)..].Trim();
                if (value.Length == 0) continue;
                if (key == "title") title ??= value;
                else if (key == "artist") artist ??= value;
                else if (key == "album_artist") albumArtist ??= value;
            }
            artist ??= albumArtist;
            return title == null && artist == null ? SongInfo.Empty : new SongInfo(title, artist, "audio tags");
        }
        catch (OperationCanceledException) { throw; }
        catch { return SongInfo.Empty; }
    }

    private static int LyricTrack(StandardMidiFile midi) =>
        midi.Events.Where(e => e.IsMeta && e.MetaType == StandardMidiFile.MetaLyric)
            .GroupBy(e => e.Track).OrderByDescending(g => g.Count()).Select(g => g.Key).FirstOrDefault(-1);

    private static string Tidy(string s) =>
        new string(s.Where(c => !char.IsControl(c)).ToArray()).Trim().Trim('/', '\\').Trim();

    /// <summary>True if <paramref name="text"/> looks like a real title or artist.</summary>
    internal static bool IsUsable(string? text)
    {
        if (string.IsNullOrWhiteSpace(text)) return false;
        var t = text.Trim();
        if (t.Length < 2 || t.Length > 100) return false;
        if (!t.Any(char.IsLetterOrDigit)) return false;
        if (GenericNames.Contains(t)) return false;
        var lower = t.ToLowerInvariant();
        return !JunkFragments.Any(j => lower.Contains(j, StringComparison.Ordinal));
    }
}
